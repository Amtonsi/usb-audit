"""Offline vector diagrams for the USB-Audit operator manual."""
from html import escape


def label(x, y, lines):
    # Each SVG line has a fixed baseline so the printed diagram matches the screen.
    first = y + 5 - (len(lines) - 1) * 10.5
    return '<text class="flow-text" text-anchor="middle">' + ''.join(
        f'<tspan x="{x}" y="{first + i * 21:g}">{escape(line)}</tspan>'
        for i, line in enumerate(lines)
    ) + '</text>'


def node(shape, x, y, w, h, *lines):
    if shape == 'decision':
        points = f'{x},{y-h/2:g} {x+w/2:g},{y} {x},{y+h/2:g} {x-w/2:g},{y}'
        outline = f'<polygon points="{points}"/>'
    else:
        radius = h / 2 if shape == 'end' else 5
        outline = f'<rect x="{x-w/2:g}" y="{y-h/2:g}" width="{w}" height="{h}" rx="{radius:g}"/>'
    return f'<g class="flow-node {shape}">{outline}{label(x, y, lines)}</g>'


def figure(key, title, summary, description, height, nodes, paths, branches):
    marker = f'arrow-{key}'
    arrows = ''.join(f'<path class="flow-edge" d="{d}" marker-end="url(#{marker})"/>' for d in paths)
    tags = ''.join(f'<text class="flow-branch" text-anchor="middle" x="{x}" y="{y}">{escape(s)}</text>'
                   for x, y, s in branches)
    boxes = ''.join(node(*item) for item in nodes)
    return f'''<figure class="flow-figure">
<figcaption><h3 id="heading-{key}">{escape(title)}</h3><p>{escape(summary)}</p></figcaption>
<div class="flow-scroll" tabindex="0" role="region" aria-labelledby="heading-{key}">
<svg class="audit-flow" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 660 {height}"
    role="img" aria-labelledby="title-{key} desc-{key}">
<title id="title-{key}">{escape(title)}</title><desc id="desc-{key}">{escape(description)}</desc>
<defs><marker id="{marker}" viewBox="0 0 10 8" refX="9" refY="4" markerWidth="8" markerHeight="7" orient="auto"><path d="M0 0 L10 4 L0 8 Z" fill="#32645e"/></marker></defs>
{arrows}{boxes}{tags}</svg></div></figure>'''


